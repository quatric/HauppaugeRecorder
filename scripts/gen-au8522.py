#!/usr/bin/env python3
"""
Generates the AU8522 decoder files used by src/tv_usb.cpp, the libusb driver of the macOS TV helper, from the
Linux kernel's au8522 driver:

    python3 scripts/gen-au8522.py [--priv au8522_priv.h --dec au8522_decoder.c] --regs > src/au8522_regs.h
    python3 scripts/gen-au8522.py [--dec au8522_decoder.c] --init > src/au8522_init.h

  au8522_regs.h  the register names and the video/audio filter coefficient tables
  au8522_init.h  the decoder's setup sequences (input modes, picture defaults, audio), with the kernel's I2C calls
                 turned into calls on an Au8522Io

Without --priv/--dec the two kernel files are fetched from GitHub. They are GPL-2.0-or-later, so the generated
files are too (they say so). They are used only by the macOS helper, a separate program the app talks to over
pipes (docs/TVHELPER.md).
"""
import re
import sys
import urllib.request

BASE = "https://raw.githubusercontent.com/torvalds/linux/master/drivers/media/dvb-frontends/"

LICENSE_HEAD = """/* SPDX-License-Identifier: GPL-2.0-or-later */
/*
 * %s
 *
 * GENERATED by scripts/gen-au8522.py from the Linux kernel's drivers/media/dvb-frontends/au8522_priv.h and
 * au8522_decoder.c, which are
 *     Copyright (C) 2008 Steven Toth <stoth@linuxtv.org>
 *     Copyright (C) 2008 Devin Heitmueller <dheitmueller@linuxtv.org>
 *     Copyright (C) 2005-2008 Auvitek International, Ltd.
 * and licensed GPL-2.0-or-later. Do not edit; regenerate.
 */
"""


def arg(name):
    if name in sys.argv:
        return sys.argv[sys.argv.index(name) + 1]
    return None


def get(name, path):
    if path:
        return open(path, encoding="utf-8").read()
    return urllib.request.urlopen(BASE + name, timeout=60).read().decode("utf-8")


def regs(priv, dec):
    out = [LICENSE_HEAD % "AU8522 register names and filter coefficient tables.", "#ifndef AU8522_REGS_H\n#define AU8522_REGS_H\n\n"]
    defs = []
    for line in priv.splitlines():
        m = re.match(r"^#define\s+(AU8522_\w+)\s+(0x[0-9A-Fa-f]+|\d+)\s*(?:/\*.*\*/)?\s*$", line)
        if m:
            defs.append("#define %s %s" % (m.group(1), m.group(2)))
    out.append("\n".join(defs) + "\n\n")

    def table(name):
        m = re.search(r"static const struct au8522_register_config " + name + r"\[\] = \{(.*?)\n\};", dec, re.S)
        if not m:
            sys.exit("table %s not found" % name)
        rows = re.findall(r"\{\s*(AU8522_\w+|0x[0-9A-Fa-f]+),\s*\{([^}]*)\}\s*\}", m.group(1))
        body = ",\n".join("    { %s, { %s } }" % (r, v.strip()) for r, v in rows)
        macro = "NUM_" + name.upper()
        return "static const au8522_register_config %s[] = {\n%s,\n};\n#define %s ((int)(sizeof(%s) / sizeof(%s[0])))\n\n" % (
            name, body, macro, name, name)

    out.append("/* filter_coef reg_val[type]: 0=ATV RF, 1=ATV RF13, 2=CVBS, 3=S-Video, 4=PAL, 5=CVBS13, 6=SVideo13 */\n")
    out.append("struct au8522_register_config { unsigned short reg_name; unsigned char reg_val[8]; };\n")
    out.append("typedef struct au8522_register_config au8522_register_config;\n\n")
    out.append(table("filter_coef"))
    out.append(table("lpfilter_coef"))
    out.append("#endif\n")
    return "".join(out)


def functions(dec):
    names = ["setup_decoder_defaults", "au8522_setup_cvbs_mode", "au8522_setup_cvbs_tuner_mode", "au8522_setup_svideo_mode",
             "disable_audio_input", "set_audio_input", "au8522_video_set"]
    out = []
    for n in names:
        m = re.search(r"^static void " + n + r"\(.*?^\}\n", dec, re.S | re.M)
        if not m:
            sys.exit("function %s not found" % n)
        t = m.group(0)
        t = t.replace("struct au8522_state *state", "Au8522Io &io")
        t = re.sub(r"au8522_writereg\(state,\s*", "io.wr(", t)
        t = re.sub(r"\(state([,)])", r"(io\1", t)  # calls that pass state on
        t = t.replace("msleep(", "io.msleep(")
        t = re.sub(r"printk\(KERN_ERR\s*", "io.err(", t)
        t = t.replace("state->std == V4L2_STD_PAL_M", "io.pal_m")
        t = t.replace("state->aud_input", "io.aud_input").replace("state->vid_input", "io.vid_input")
        t = t.replace("u8 input_mode", "uint8_t input_mode")
        out.append(t)
    return "\n".join(out)


def init(dec):
    head = LICENSE_HEAD % "AU8522 video decoder setup: the register sequences of the kernel's au8522_decoder.c."
    head += """#ifndef AU8522_INIT_H
#define AU8522_INIT_H
#include <stdint.h>
#include "au8522_regs.h"

enum { AU8522_COMPOSITE_CH1 = 1, AU8522_COMPOSITE_CH2, AU8522_COMPOSITE_CH3, AU8522_COMPOSITE_CH4, AU8522_COMPOSITE_CH4_SIF,
       AU8522_SVIDEO_CH13, AU8522_SVIDEO_CH24 };
enum { AU8522_AUDIO_NONE, AU8522_AUDIO_SIF };

struct Au8522Io {
    virtual ~Au8522Io() {}
    virtual void wr(uint16_t reg, uint8_t value) = 0;
    virtual void msleep(int ms) = 0;
    virtual void err(const char *fmt, ...) = 0;
    bool pal_m = false;
    int vid_input = AU8522_COMPOSITE_CH1, aud_input = AU8522_AUDIO_NONE;
};

"""
    body = functions(dec).replace("static void", "static inline void")
    left = [l for l in body.splitlines() if re.search(r"\bstate\b", l)]
    if left:
        sys.exit("untranslated 'state' left in:\n" + "\n".join(left))
    return head + body + "\n#endif\n"


def main():
    dec = get("au8522_decoder.c", arg("--dec"))
    if "--init" in sys.argv:
        sys.stdout.write(init(dec))
    else:
        sys.stdout.write(regs(get("au8522_priv.h", arg("--priv")), dec))


main()
